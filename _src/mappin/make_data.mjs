// Builds _src/mappin/data.js for Pin the Map: the world map as SVG paths plus every question (capitals, cities,
// landmarks) with names, coordinates and notes. Run after editing places.json or capitals.json:
//   npm install --prefix /tmp/mapdeps world-atlas@2.0.2 topojson-client@3.1.0
//   node _src/mappin/make_data.mjs /tmp/mapdeps
// The map is Natural Earth 1:110m (public domain) from the world-atlas package, drawn in a plain
// longitude/latitude projection: x = longitude, y = -latitude.
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const deps = process.argv[2] || '/tmp/mapdeps';
const require = createRequire(path.join(deps, 'node_modules', 'x.js'));
const topo = require('topojson-client');
const world = require('world-atlas/countries-110m.json');

function pathOf(geom) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.type === 'MultiPolygon' ? geom.coordinates : geom.type === 'MultiLineString' ? [geom.coordinates] : [[geom.coordinates]];
  let d = '';
  for (const poly of polys) for (const ring of poly) {
    let last = '', n = 0, seg = '';
    for (const [lon, lat] of ring) {
      const p = `${+lon.toFixed(1)} ${+(-lat).toFixed(1)}`;
      if (p === last) continue;
      seg += (n ? 'L' : 'M') + p; last = p; n++;
    }
    if (n >= 2) d += seg + (geom.type.endsWith('Polygon') ? 'Z' : '');
  }
  return d.replace(/ -/g, '-');
}
const land = pathOf(topo.merge(world, world.objects.countries.geometries));
const borders = pathOf(topo.mesh(world, world.objects.countries, (a, b) => a !== b));

const countries = JSON.parse(fs.readFileSync(path.join(here, '../webgames/countries.json'), 'utf8')).countries;
const caps = JSON.parse(fs.readFileSync(path.join(here, 'capitals.json'), 'utf8')).capitals;
const places = JSON.parse(fs.readFileSync(path.join(here, 'places.json'), 'utf8'));
const byCode = Object.fromEntries(countries.map((c) => [c.code, c]));
// [English, Korean, English with "the" where it needs one: the Philippines, the United States]
const names = Object.fromEntries(countries.map((c) => [c.code, [c.name.en, c.name.ko, (c.the ? 'the ' : '') + c.name.en]]));

const q = [];
for (const c of countries) {
  if (!c.capital || !caps[c.code]) continue;
  q.push({ k: 'c', en: c.capital.en, ko: c.capital.ko, cc: [c.code], r: c.region, lv: c.capitalLevel, lat: caps[c.code][0], lon: caps[c.code][1] });
}
for (const [kind, list] of [['t', places.cities], ['l', places.landmarks]]) for (const p of list) {
  const cc = Array.isArray(p.cc) ? p.cc : [p.cc];
  cc.forEach((x) => { if (!byCode[x]) throw new Error('unknown country ' + x + ' for ' + p.en); });
  q.push({ k: kind, en: p.en, ko: p.ko, cc, r: byCode[cc[0]].region, lat: p.lat, lon: p.lon, n: [p.note.en, p.note.ko] });
}
const out = '/* Generated by _src/mappin/make_data.mjs from places.json, capitals.json and ../webgames/countries.json: do not edit by hand.\n' +
  '   Map: Natural Earth 1:110m (public domain). Capital and city coordinates: GeoNames (CC BY 4.0). */\n' +
  'window.PIN_DATA = ' + JSON.stringify({ land, borders, names, q }) + ';\n';
fs.writeFileSync(path.join(here, 'data.js'), out);
console.log('data.js', (out.length / 1024).toFixed(1) + ' KB,', q.length, 'questions (land', land.length, 'borders', borders.length, ')');
